package mesh

import (
	"strconv"
	"strings"
)

// opencode_tui.go — the mesh status panel for opencode V2's terminal UI, the
// counterpart of Claude Code's status line. A TUI plugin is a folder holding
// tui.js; opencode supplies @opentui/solid and solid-js, so the file needs no
// build step. It shows the agent, its pool and the pending work in the session
// sidebar, and one compact line in the prompt footer, refreshed every
// StatusLineRefreshSeconds by running `meshctl hook status-line --json` (local
// file reads, no model calls). It loads only in the interactive TUI, never in
// `opencode run`. V1 has no TUI plugins, so a V1 agent gets none.

const opencodeTUIRel = ".opencode/plugins/meshctl-tui/tui.js"

// opencodeTUIPlugin is the panel source with the refresh interval filled in.
var opencodeTUIPlugin = strings.Replace(opencodeTUIJS, "__REFRESH_MS__", strconv.Itoa(StatusLineRefreshSeconds*1000), 1)

const opencodeTUIJS = `// meshctl mesh integration for opencode: status panel (generated by ` + "`meshctl agent new/onboard`" + `).
// Shows the agent, its pool and the pending work waiting on you, from
// ` + "`meshctl hook status-line --json`" + `. Regenerated on onboard and pool upgrade.
import { createElement, insert } from "@opentui/solid";
import { createSignal } from "solid-js";
import { execFile } from "node:child_process";

const REFRESH_MS = __REFRESH_MS__;
const cwd = process.cwd();

const groupText = (g) => (g.alert ? "! " : "") + g.label + " " + g.value;

export default {
  id: "meshctl-tui",
  setup(api) {
    const [report, setReport] = createSignal(null);
    let busy = false;
    const poll = () => {
      if (busy) return;
      busy = true;
      try {
        const child = execFile("meshctl", ["hook", "status-line", "--json"], { cwd, timeout: 5000 }, (err, out) => {
          busy = false;
          if (err) return; // fail-open: keep the last report
          try { setReport(JSON.parse(out)); } catch {}
        });
        child.stdin.end(JSON.stringify({ cwd }));
      } catch { busy = false; }
    };
    poll();
    const timer = setInterval(poll, REFRESH_MS);

    // Sidebar: the agent and pool, then one line per group with its phrase.
    const sidebar = () => {
      const r = report();
      if (!r || !r.agent) return "";
      const lines = [r.agent + " · " + r.pool];
      if (r.groups.length === 0) lines.push("  nothing pending");
      for (const g of r.groups) {
        lines.push("  " + groupText(g));
        if (g.say) lines.push('    say "' + g.say + '"');
      }
      return lines.join("\n");
    };
    // Prompt footer: one compact line.
    const footer = () => {
      const r = report();
      if (!r || !r.agent) return "";
      const gs = r.groups.map(groupText);
      return r.agent + " · " + (gs.length ? gs.join(" · ") : "nothing pending");
    };
    const view = (text) => () => {
      const el = createElement("text");
      insert(el, text);
      return el;
    };
    const off = [
      api.ui.slot({ append: "sidebar.content", render: view(sidebar) }),
      api.ui.slot({ append: "prompt.footer", render: view(footer) }),
    ];
    return () => {
      clearInterval(timer);
      off.forEach((f) => f());
    };
  },
};
`
